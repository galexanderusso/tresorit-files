import { Client } from '../tresorit-connector/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import { StdioClientTransport } from '../tresorit-connector/node_modules/@modelcontextprotocol/sdk/dist/esm/client/stdio.js';
import fs from 'node:fs';
const SERVER = process.env.SERVER || '/home/tester/build/tresorit-connector/server/index.js';
const DATA = '/home/tester/build/mock/data-pf'; fs.rmSync(DATA, { recursive: true, force: true });
const env = { ...process.env, TRESORIT_ROOT: '/home/tester/build/mock/Tresors', TRESORIT_DATA_DIR: DATA, TRESORIT_INDEX_DELAY_MS: '999999' }; delete env.TRESORIT_PREFLIGHT_GATE;
const transport = new StdioClientTransport({ command: 'node', args: [SERVER], env, stderr: 'inherit' });
const client = new Client({ name: 'pf', version: '1' }, { capabilities: {} });
await client.connect(transport);
const call = async (n, a = {}) => { const t0 = Date.now(); const r = await client.callTool({ name: 'tresorit_' + n, arguments: a }, undefined, { timeout: 170000 }); return { text: r.content.map((c) => c.text || '').join('\n'), isError: !!r.isError, ms: Date.now() - t0 }; };
let r = await call('write_file', { path: 'Birch Labs/gate-test.txt', content: 'x' });
console.log('before check, write ->', r.isError ? 'REFUSED: ' + r.text.slice(0, 120) : 'ALLOWED');
r = await call('preflight');
console.log(`\n[preflight took ${r.ms} ms]\n` + r.text);
r = await call('write_file', { path: 'Birch Labs/gate-test.txt', content: 'x' });
console.log('\nafter check, write ->', r.isError ? 'REFUSED: ' + r.text.slice(0, 120) : 'ALLOWED');
fs.rmSync('/home/tester/build/mock/Tresors/Birch Labs/gate-test.txt', { force: true });
console.log('scratch folder removed:', fs.readdirSync(DATA + '/preflight').length === 0, '| files in data folder:', fs.readdirSync(DATA).join(', '));
await client.close();
